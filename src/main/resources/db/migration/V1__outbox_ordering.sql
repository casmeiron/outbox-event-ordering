CREATE TABLE customer_order (
    id UUID PRIMARY KEY,
    customer_ref VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL,
    version BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

-- id is a database identity. It is allocated when the INSERT statement runs,
-- not when the transaction commits, so it is not a commit-order clock.
CREATE TABLE outbox_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    aggregate_id UUID NOT NULL,
    aggregate_version BIGINT NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    payload TEXT NOT NULL,
    shard INT NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL,
    source_commit_time TIMESTAMPTZ NOT NULL,
    published_at TIMESTAMPTZ NULL,
    claimed_by VARCHAR(80) NULL,
    claimed_at TIMESTAMPTZ NULL,
    CONSTRAINT uq_outbox_aggregate_version UNIQUE (aggregate_id, aggregate_version)
);

CREATE INDEX ix_outbox_unpublished ON outbox_event (id) WHERE published_at IS NULL;
CREATE INDEX ix_outbox_shard_unpublished ON outbox_event (shard, aggregate_id, aggregate_version)
    WHERE published_at IS NULL;

CREATE TABLE order_projection (
    order_id UUID PRIMARY KEY,
    customer_ref VARCHAR(255) NULL,
    status VARCHAR(32) NULL,
    applied_version BIGINT NOT NULL,
    payment_ref VARCHAR(255) NULL,
    tracking_number VARCHAR(255) NULL,
    regressed BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE projection_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL,
    aggregate_version BIGINT NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    status_after VARCHAR(32) NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX ix_projection_log_order ON projection_log (order_id, id);

CREATE TABLE parked_event (
    order_id UUID NOT NULL,
    aggregate_version BIGINT NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    payload TEXT NOT NULL,
    parked_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (order_id, aggregate_version)
);

CREATE TABLE relay_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_id UUID NOT NULL,
    aggregate_version BIGINT NOT NULL,
    kafka_key TEXT NOT NULL,
    mode VARCHAR(16) NOT NULL,
    worker_slot INT NOT NULL,
    published_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX ix_relay_log_aggregate ON relay_log (aggregate_id, id);
